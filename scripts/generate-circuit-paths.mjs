#!/usr/bin/env node

/**
 * One-time script to generate circuit SVG path data from GeoJSON.
 *
 * Fetches F1 circuit GeoJSON from GitHub, normalises coordinates into
 * a 0 0 100 100 viewBox, and writes TypeScript to src/lib/data/circuit-paths.ts.
 *
 * Usage: node scripts/generate-circuit-paths.mjs
 */

import { writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const GEOJSON_URL =
  "https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson";

// Map GeoJSON circuit names → OpenF1 circuit_short_name
const NAME_MAP = {
  "Bahrain International Circuit": "Sakhir",
  "Jeddah Corniche Circuit": "Jeddah",
  "Albert Park Circuit": "Melbourne",
  "Suzuka International Racing Course": "Suzuka",
  "Shanghai International Circuit": "Shanghai",
  "Miami International Autodrome": "Miami",
  "Autodromo Enzo e Dino Ferrari": "Imola",
  "Circuit de Monaco": "Monte Carlo",
  "Circuit de Barcelona-Catalunya": "Catalunya",
  "Circuit Gilles-Villeneuve": "Montreal",
  "Red Bull Ring": "Spielberg",
  "Silverstone Circuit": "Silverstone",
  "Hungaroring": "Hungaroring",
  "Circuit de Spa-Francorchamps": "Spa-Francorchamps",
  "Circuit Zandvoort": "Zandvoort",
  "Autodromo Nazionale Monza": "Monza",
  "Baku City Circuit": "Baku",
  "Marina Bay Street Circuit": "Singapore",
  "Circuit of the Americas": "Austin",
  "Autódromo Hermanos Rodríguez": "Mexico City",
  "Autódromo José Carlos Pace": "Interlagos",
  "Autódromo José Carlos Pace - Interlagos": "Interlagos",
  "Las Vegas Strip Circuit": "Las Vegas",
  "Las Vegas Street Circuit": "Las Vegas",
  "Lusail International Circuit": "Lusail",
  "Losail International Circuit": "Lusail",
  "Yas Marina Circuit": "Yas Marina Circuit",
};

const PADDING = 5; // percent padding inside the viewBox

async function main() {
  console.log("Fetching GeoJSON…");
  const res = await fetch(GEOJSON_URL);
  if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
  const geojson = await res.json();

  const circuits = {};

  for (const feature of geojson.features) {
    const name = feature.properties?.Name ?? feature.properties?.name;
    const shortName = NAME_MAP[name];
    if (!shortName) {
      console.log(`  Skipping unknown circuit: ${name}`);
      continue;
    }

    // Extract coordinates – handle both Polygon and LineString
    let coords;
    const geom = feature.geometry;
    if (geom.type === "MultiLineString") {
      coords = geom.coordinates.flat();
    } else if (geom.type === "LineString") {
      coords = geom.coordinates;
    } else if (geom.type === "Polygon") {
      coords = geom.coordinates[0];
    } else if (geom.type === "MultiPolygon") {
      coords = geom.coordinates[0][0];
    } else {
      console.log(`  Skipping ${name}: unsupported geometry ${geom.type}`);
      continue;
    }

    if (!coords || coords.length < 3) {
      console.log(`  Skipping ${name}: too few coordinates (${coords?.length})`);
      continue;
    }

    // coords are [lon, lat] – normalise to viewBox with padding
    const lons = coords.map((c) => c[0]);
    const lats = coords.map((c) => c[1]);
    const minLon = Math.min(...lons);
    const maxLon = Math.max(...lons);
    const minLat = Math.min(...lats);
    const maxLat = Math.max(...lats);

    const rangeX = maxLon - minLon || 1e-6;
    const rangeY = maxLat - minLat || 1e-6;

    const usable = 100 - 2 * PADDING;

    // Maintain aspect ratio
    const scaleX = usable / rangeX;
    const scaleY = usable / rangeY;
    const scale = Math.min(scaleX, scaleY);

    const offsetX = PADDING + (usable - rangeX * scale) / 2;
    const offsetY = PADDING + (usable - rangeY * scale) / 2;

    const points = coords.map(([lon, lat]) => {
      const x = offsetX + (lon - minLon) * scale;
      // Flip Y: lat increases up but SVG y increases down
      const y = offsetY + (maxLat - lat) * scale;
      return [Math.round(x * 100) / 100, Math.round(y * 100) / 100];
    });

    const pathParts = points.map(([x, y], i) =>
      i === 0 ? `M ${x} ${y}` : `L ${x} ${y}`
    );
    pathParts.push("Z");

    circuits[shortName] = {
      viewBox: "0 0 100 100",
      path: pathParts.join(" "),
      name,
    };
    console.log(`  ✓ ${shortName} (${name}) — ${points.length} points`);
  }

  // Generate TypeScript source
  const entries = Object.entries(circuits)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(
      ([key, val]) =>
        `  ${JSON.stringify(key)}: {\n    viewBox: ${JSON.stringify(val.viewBox)},\n    path: ${JSON.stringify(val.path)},\n    name: ${JSON.stringify(val.name)},\n  }`
    )
    .join(",\n");

  const ts = `// Auto-generated by scripts/generate-circuit-paths.mjs — do not edit manually.

export interface CircuitPath {
  viewBox: string;
  path: string;
  name: string;
}

export const CIRCUIT_PATHS: Record<string, CircuitPath> = {
${entries},
};
`;

  const outPath = resolve(__dirname, "../src/lib/data/circuit-paths.ts");
  writeFileSync(outPath, ts, "utf-8");
  console.log(`\nWrote ${Object.keys(circuits).length} circuits → ${outPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
